    public function tokenize(Request $request): JsonResponse
    {
        $text = $request->validate(['text' => 'required|string|max:5000'])['text'];
        $map = $this->content->wordMap();
        $tokens = $this->content->tokenize($text);

        return response()->json(['data' => [
            'words' => $tokens,
            'unknown' => array_values(array_unique(array_filter($tokens, fn ($t) => ! array_key_exists($t, $map)))),
        ]]);
    }

    public function validateContent(): JsonResponse
    {
        return response()->json($this->content->validate());
    }

    public function export(): JsonResponse
    {
        return response()->json([
            'dictionary' => $this->content->dictionary(),
            'vocabulary' => (object) $this->content->vocabulary(),
            'lessons' => \App\Models\Lesson::orderBy('number')->get()->map->toLegacy(),
            'readings' => $this->content->readings(includeUnpublished: true),
        ], 200, [], JSON_UNESCAPED_UNICODE);
    }
}
